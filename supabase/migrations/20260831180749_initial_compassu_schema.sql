create extension if not exists pgcrypto;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  first_name text,
  last_name text,
  graduation_year integer,
  state text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.assessment_questions (
  id integer generated by default as identity primary key,
  question_number integer not null unique check (question_number between 1 and 80),
  dimension text not null check (dimension in ('interests','strengths','personality','values','work_environment','academic_preferences')),
  question_text text not null,
  response_type text not null default 'likert5',
  scoring_key jsonb not null default '{}'::jsonb,
  is_active boolean not null default true
);

create table public.assessment_attempts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  status text not null default 'in_progress' check (status in ('in_progress','completed')),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  scoring_version text not null default 'v1'
);

create table public.assessment_responses (
  id uuid primary key default gen_random_uuid(),
  attempt_id uuid not null references public.assessment_attempts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  question_id integer not null references public.assessment_questions(id),
  response_value jsonb not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(attempt_id, question_id)
);

create table public.majors (
  id integer generated by default as identity primary key,
  name text not null unique,
  description text,
  cip_code text,
  career_cluster text,
  active boolean not null default true
);

create table public.occupations (
  id integer generated by default as identity primary key,
  name text not null,
  soc_code text unique,
  description text,
  median_salary numeric,
  salary_year integer,
  outlook_percent numeric,
  source text default 'BLS'
);

create table public.major_occupations (
  major_id integer not null references public.majors(id) on delete cascade,
  occupation_id integer not null references public.occupations(id) on delete cascade,
  relevance_weight numeric not null default 1,
  primary key (major_id, occupation_id)
);

create table public.institutions (
  id bigint primary key,
  name text not null,
  city text,
  state text,
  website text,
  source text default 'College Scorecard'
);

create table public.institution_majors (
  institution_id bigint not null references public.institutions(id) on delete cascade,
  major_id integer not null references public.majors(id) on delete cascade,
  primary key (institution_id, major_id)
);

create table public.major_matches (
  id uuid primary key default gen_random_uuid(),
  attempt_id uuid not null references public.assessment_attempts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  major_id integer not null references public.majors(id),
  match_score numeric not null check (match_score between 0 and 100),
  rank integer not null,
  explanation text,
  created_at timestamptz not null default now(),
  unique(attempt_id, major_id)
);

create index assessment_attempts_user_idx on public.assessment_attempts(user_id);
create index assessment_responses_user_idx on public.assessment_responses(user_id);
create index assessment_responses_attempt_idx on public.assessment_responses(attempt_id);
create index major_matches_user_idx on public.major_matches(user_id);
create index major_matches_attempt_idx on public.major_matches(attempt_id);

